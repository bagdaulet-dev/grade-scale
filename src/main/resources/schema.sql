CREATE TABLE IF NOT EXISTS workspaces (
  owner CHAR(64) NOT NULL PRIMARY KEY,
  expires_at TIMESTAMP(6) NOT NULL,
  INDEX workspace_expiry (expires_at)
);
CREATE TABLE IF NOT EXISTS courses (
  id CHAR(36) NOT NULL PRIMARY KEY,
  owner CHAR(64) NOT NULL,
  name VARCHAR(80) NOT NULL,
  code VARCHAR(20) NOT NULL DEFAULT '',
  created_at TIMESTAMP(6) NOT NULL,
  INDEX course_owner (owner, created_at),
  FOREIGN KEY (owner) REFERENCES workspaces(owner) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS assessments (
  id CHAR(36) NOT NULL PRIMARY KEY,
  course_id CHAR(36) NOT NULL,
  name VARCHAR(60) NOT NULL,
  score DECIMAL(5,2) NOT NULL,
  weight DECIMAL(5,2) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
  INDEX assessment_course (course_id, created_at),
  CHECK (score >= 0 AND score <= 100),
  CHECK (weight > 0 AND weight <= 100)
);

-- Spring Session JDBC schema, adapted from its Apache-2.0-licensed MySQL script.
CREATE TABLE IF NOT EXISTS SPRING_SESSION (
  PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
  SESSION_ID CHAR(36) NOT NULL,
  CREATION_TIME BIGINT NOT NULL,
  LAST_ACCESS_TIME BIGINT NOT NULL,
  MAX_INACTIVE_INTERVAL INT NOT NULL,
  EXPIRY_TIME BIGINT NOT NULL,
  PRINCIPAL_NAME VARCHAR(100),
  UNIQUE INDEX SPRING_SESSION_IX1 (SESSION_ID),
  INDEX SPRING_SESSION_IX2 (EXPIRY_TIME),
  INDEX SPRING_SESSION_IX3 (PRINCIPAL_NAME)
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC;
CREATE TABLE IF NOT EXISTS SPRING_SESSION_ATTRIBUTES (
  SESSION_PRIMARY_ID CHAR(36) NOT NULL,
  ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
  ATTRIBUTE_BYTES BLOB NOT NULL,
  PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
  FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC;
